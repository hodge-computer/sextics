def _compositions6(degree):
    """All 6-tuples of nonnegative integers summing to degree, in lex order."""
    out = []

    def extend(i, remaining, current):
        if i == 5:
            out.append(tuple(current + [remaining]))
            return
        for a in range(remaining + 1):
            extend(i + 1, remaining - a, current + [a])

    extend(0, degree, [])
    return out


def _h64_orbit(e):
    """The four images of an exponent tuple under <sigma_0, sigma_1>."""
    e0 = (e[3], e[1], e[2], e[0], e[4], e[5])
    e1 = (e[0], e[4], e[2], e[3], e[1], e[5])
    e01 = (e[3], e[4], e[2], e[0], e[1], e[5])
    return e, e0, e1, e01


def _h64_orbits(degree, s0, s1, y_parity, reduced=False):
    """Basis of S_degree^(s0, s1, y_parity) (P-even), optionally with exponents <= 4."""
    seen, basis = set(), []
    for e in _compositions6(degree):
        if reduced and max(e) > 4:
            continue
        if (e[0] + e[3]) % 2 or (e[1] + e[4]) % 2 or (e[2] + e[5]) % 2:
            continue
        if (e[3] + e[4] + e[5]) % 2 != y_parity:
            continue
        rep = min(_h64_orbit(e))
        if rep in seen:
            continue
        seen.add(rep)
        r, r0, r1, r01 = _h64_orbit(rep)
        d = {}
        for m, sg in ((r, 1), (r0, s0), (r1, s1), (r01, s0 * s1)):
            d[m] = d.get(m, 0) + sg
        d = {m: c for m, c in d.items() if c}
        if d:
            g = min(abs(c) for c in d.values())
            basis.append({m: (c // g) % P for m, c in d.items()})
    return basis


def _echelon(M):
    """Row-echelon elimination modulo P, in place; returns (rank, pivot_columns)."""
    M %= P
    rank, pivots = 0, []
    nrows, ncols = M.shape
    for c in range(ncols):
        nonzero = np.nonzero(M[rank:, c])[0]
        if len(nonzero) == 0:
            continue
        r = rank + int(nonzero[0])
        if r != rank:
            M[[rank, r]] = M[[r, rank]]
        inv = pow(int(M[rank, c]), P - 2, P)
        if inv != 1:
            M[rank, c:] = (M[rank, c:] * inv) % P
        rows = np.nonzero(M[rank + 1:, c])[0] + (rank + 1)
        if len(rows):
            M[rows, c:] = (M[rows, c:] - M[rows, c:c + 1] * M[rank:rank + 1, c:]) % P
        pivots.append(c)
        rank += 1
        if rank == nrows:
            break
    return rank, pivots


def paired_exchange_higgs():
    """Weight-four Higgs checks at the Fermat member for the paired-exchange group H."""
    assert len(_h64_orbits(6, 1, 1, 0, reduced=False)) == 40
    sectors = {}
    for s0 in (1, -1):
        for s1 in (1, -1):
            # det(sigma_0) = det(sigma_1) = -1, so residue character is (-s0, -s1).
            label = f"({'+' if -s0 > 0 else '-'},{'+' if -s1 > 0 else '-'})"
            sectors[label] = [len(_h64_orbits(d, s0, s1, 1, reduced=True)) for d in (6, 12, 18)]
    assert sectors == {'(+,+)': [3, 26, 3], '(+,-)': [11, 51, 11],
                       '(-,+)': [11, 51, 11], '(-,-)': [33, 102, 33]}

    G = _h64_orbits(6, 1, 1, 0, reduced=True)
    V = _h64_orbits(6, 1, 1, 1, reduced=True)
    W = _h64_orbits(12, 1, 1, 1, reduced=True)
    assert (len(G), len(V), len(W)) == (36, 33, 102)

    # Check surjectivity of multiplication G x V -> W in R(F0).
    W_rep = {min(d): (j, pow(d[min(d)], P - 2, P)) for j, d in enumerate(W)}
    rows_gv = []
    for g in G:
        for v in V:
            vec = np.zeros(len(W), dtype=np.int32)
            for e1, c1 in g.items():
                for e2, c2 in v.items():
                    e = tuple(x + y for x, y in zip(e1, e2))
                    if max(e) <= 4 and e in W_rep:
                        j, inv_w = W_rep[e]
                        vec[j] = (vec[j] + c1 * c2 * inv_w) % P
            if vec.any():
                rows_gv.append(vec)
    rank_gv, _ = _echelon(np.array(rows_gv, dtype=np.int32))
    assert rank_gv == 102

    # Build all reduced products g*h (g, h in G) and check P^T H_q = H_q P on three combinations.
    gh_polys = []
    for i in range(len(G)):
        for j in range(i, len(G)):
            d = {}
            for e1, c1 in G[i].items():
                for e2, c2 in G[j].items():
                    e = tuple(x + y for x, y in zip(e1, e2))
                    if max(e) <= 4:
                        d[e] = (d.get(e, 0) + c1 * c2) % P
            d = {e: c for e, c in d.items() if c}
            if d:
                gh_polys.append(d)

    n = len(V)
    eq_rows = []
    idx = np.arange(n) * n
    for r in range(3):
        q = {}
        for k, d in enumerate(gh_polys):
            wt = pow(k + 1, r, P)
            for e, c in d.items():
                q[e] = (q.get(e, 0) + wt * c) % P
        q = {e: c for e, c in q.items() if c}
        H = np.zeros((n, n), dtype=np.int32)
        for a_i, va in enumerate(V):
            qa = {}
            for e1, c1 in q.items():
                for e2, c2 in va.items():
                    e = tuple(x + y for x, y in zip(e1, e2))
                    if max(e) <= 4:
                        qa[e] = (qa.get(e, 0) + c1 * c2) % P
            for b_i in range(a_i, n):
                total = 0
                for e2, c2 in V[b_i].items():
                    comp = tuple(4 - x for x in e2)
                    if comp in qa:
                        total = (total + qa[comp] * c2) % P
                H[a_i, b_i] = H[b_i, a_i] = total
        for i in range(n):
            for j in range(i + 1, n):
                row = np.zeros(n * n, dtype=np.int32)
                row[idx + i] = (row[idx + i] + H[:, j]) % P
                row[idx + j] = (row[idx + j] - H[i, :]) % P
                if row.any():
                    eq_rows.append(row)

    comm_rank, _ = _echelon(np.array(eq_rows, dtype=np.int32))
    assert comm_rank == n * n - 1
    return {'prime': P, 'coefficients': 40, 'sectors': sectors, 'directions': len(G),
            'h31Dimension': n, 'h22Dimension': len(W), 'multiplicationRank': rank_gv,
            'commutantRank': comm_rank, 'solutionDimension': n * n - comm_rank}


def paired_exchange_family():
    """Saturated dimension and contraction ranks of the paired-exchange coefficient family."""
    basis = _h64_orbits(6, 1, 1, 0)
    assert len(basis) == 40
    columns = {e: i for i, e in enumerate(_compositions6(6))}

    def rank_of(polys):
        M = np.zeros((len(polys), len(columns)), dtype=np.int32)
        for i, f in enumerate(polys):
            for e, c in f.items():
                M[i, columns[e]] = c % P
        return _echelon(M)[0]

    # Orbit derivatives Z_i * dF0/dZ_j = 6 * Z_i * Z_j^5 of GL_3(X) x GL_3(Y) at the Fermat member.
    orbit = []
    for block in ((0, 1, 2), (3, 4, 5)):
        for i in block:
            for j in block:
                e = [0] * 6
                e[j] += 5
                e[i] += 1
                orbit.append({tuple(e): 6})
    assert rank_of(orbit) == 18
    saturated = rank_of(basis + orbit)
    assert saturated == 54

    def monomial(**powers):
        e = [0] * 6
        for name, k in powers.items():
            e['XY'.index(name[0]) * 3 + int(name[1])] = k
        return tuple(e)

    member = {}
    for i in range(3):
        member[monomial(**{f'X{i}': 6})] = 1
        member[monomial(**{f'Y{i}': 6})] = 1
        member[monomial(**{f'X{i}': 4, f'Y{i}': 2})] = 1
        member[monomial(**{f'X{i}': 2, f'Y{i}': 4})] = 1
        j, k = [m for m in range(3) if m != i]
        for square in (f'X{i}', f'Y{i}'):
            member[monomial(**{f'X{j}': 1, f'Y{j}': 1, f'X{k}': 1, f'Y{k}': 1, square: 2})] = 1
    # The member lies in S_6^H: it is a combination of the orbit sums.
    assert rank_of(basis + [member]) == 40

    def contraction_rank(x_degree):
        rows = {}
        for e, c in member.items():
            if sum(e[:3]) == x_degree:
                rows.setdefault(e[:3], {})[e[3:]] = c
        ys = sorted({y for row in rows.values() for y in row})
        M = np.array([[row.get(y, 0) for y in ys] for row in rows.values()], dtype=np.int32)
        return _echelon(M)[0]

    ranks = (contraction_rank(4), contraction_rank(2))
    assert ranks == (6, 6)
    return {'prime': P, 'coefficients': len(basis), 'orbitRank': 18, 'saturatedDimension': saturated,
            'contractionRanks': list(ranks)}


